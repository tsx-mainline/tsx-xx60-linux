#!/bin/sh
# Read TFA9890 registers (16-bit big-endian) on i2c-1 0x34/0x36 via i2ctransfer -f
# usage: tfaregs.sh [regs...]  (default 0x00-0x0f 0x41 0x46-0x49 0x70-0x73 0x80-0x8f)
REGS="$*"
[ -z "$REGS" ] && REGS="0x00 0x01 0x02 0x03 0x04 0x05 0x06 0x07 0x08 0x09 0x0a 0x0b 0x0c 0x0d 0x0e 0x0f 0x41 0x46 0x47 0x48 0x49 0x70 0x71 0x72 0x73"
for a in 0x34 0x36; do
  printf '%s:' $a
  for r in $REGS; do
    v=$(i2ctransfer -f -y 1 w1@$a $r r2 2>/dev/null | sed 's/0x//g;s/ //')
    printf ' %02x=%s' $r "${v:-??}"
  done
  echo
done
